import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { _electron, expect } from '@playwright/test';
import { createServer } from 'vite';
import { Store } from '../core/store.mjs';

const file = resolve(process.argv[2] || '');
const executablePath = process.argv[3] ? resolve(process.argv[3]) : undefined;
const root = resolve('.');
const out = join(root, '.cache', 'swipe-library-proof');
await mkdir(out, { recursive: true });
const temp = resolve(tmpdir());
const userData = await mkdtemp(join(temp, 'carrossell-swipe-proof-'));
const server = executablePath ? null : await createServer({ root, logLevel: 'error', server: { host: '127.0.0.1', port: 0 } });
let app;
try {
  const store = await new Store(join(userData, 'library')).init();
  await store.saveProfile({ brand: 'Biblioteca de teste', product: 'Teste', audience: 'Teste' });
  const project = await store.createProject({ title: 'Carrossel de teste', brief: 'Controle de artes salvas' });
  await store.saveProject({ id: project.id, slides: [{ id: 'a', title: 'Capa' }, { id: 'b', title: 'Segundo card' }] });
  const art = await readFile(join(root, 'resources', 'branding', 'icon-256.png'));
  await Promise.all(['a', 'b'].map(id => store.addImage(project.id, id, art)));
  await store.update(project.id, { textApproved: true, status: 'complete' });
  await writeFile(join(userData, 'license-state.json'), JSON.stringify({ activated: true, expiresAt: new Date(Date.now() + 90 * 86400000).toISOString() }));
  await server?.listen();
  const env = { ...process.env, PACTO_USER_DATA: userData, PACTO_AUTOPILOT_NO_TASKS: '1', PACTO_UPDATE_URL: 'http://127.0.0.1:9/' };
  delete env.ELECTRON_RUN_AS_NODE;
  delete env.PACTO_DEV_URL;
  if (server) env.PACTO_DEV_URL = `http://127.0.0.1:${server.httpServer.address().port}`;
  const open = () => _electron.launch({ executablePath, args: executablePath ? [] : ['.'], cwd: root, env });
  app = await open();
  assert.equal(await app.evaluate(({ app }) => app.isPackaged), Boolean(executablePath));
  await app.evaluate(({ dialog }) => { dialog.showMessageBox = async () => ({ response: 0 }); });
  let page = await app.firstWindow();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 1093, height: 680 });
  await page.getByRole('heading', { name: 'O que vamos criar hoje?' }).waitFor();
  await page.getByRole('textbox', { name: 'Tema ou ideia' }).fill('Tema preservado no composer');
  // Carrega um File do disco no Chromium e usa o mesmo caminho webUtils do arrastar e soltar.
  await page.evaluate(() => {
    const picker = document.createElement('input');
    picker.id = 'zip-fixture';
    picker.type = 'file';
    document.body.append(picker);
  });
  await page.locator('#zip-fixture').setInputFiles(file);
  const started = Date.now();
  await page.evaluate(() => {
    const picker = document.getElementById('zip-fixture');
    const transfer = new DataTransfer();
    transfer.items.add(picker.files[0]);
    document.querySelector('.shell').dispatchEvent(new DragEvent('drop', { dataTransfer: transfer, bubbles: true, cancelable: true }));
    picker.remove();
  });
  await expect(page.getByText('500 referências', { exact: true })).toBeVisible({ timeout: 90000 });
  const importMs = Date.now() - started;
  const cards = page.locator('.reference-card');
  await expect(cards).toHaveCount(24);
  await expect.poll(() => cards.first().locator('img').evaluate(el => el.complete && el.naturalWidth > 0)).toBe(true);
  await page.screenshot({ path: join(out, 'biblioteca.png') });
  const search = page.getByRole('textbox', { name: 'Buscar referências' });
  const { items } = await page.evaluate(() => window.pacto.request('referenceCatalog'));
  assert.equal(new Set(items.map(item => item.sourceId)).size, 500);
  assert.ok(!JSON.stringify(items).includes(';base64,'));
  const recent = items.at(-1);
  await search.fill(recent.sourceId);
  await expect(cards).toHaveCount(1);
  await expect(cards.first()).toContainText(recent.hook);
  await cards.first().getByRole('button', { name: 'Ver referência', exact: true }).click();
  const details = page.getByRole('dialog', { name: recent.hook });
  await expect(details).toBeVisible();
  await expect.poll(() => details.locator('img').evaluate(el => el.complete && el.naturalWidth > 0)).toBe(true);
  await page.keyboard.press('Escape');
  await cards.first().getByRole('button', { name: /^Usar referência/ }).click();
  await expect(page.getByRole('textbox', { name: 'Tema ou ideia' })).toHaveValue('Tema preservado no composer');
  const nav = page.getByRole('navigation', { name: 'Navegação principal' });
  await nav.getByRole('button', { name: 'Biblioteca', exact: true }).click();
  await expect(page.getByText('500 referências', { exact: true })).toBeVisible();
  await page.getByRole('navigation', { name: 'Paginação da Biblioteca' }).getByRole('button', { name: 'Próxima' }).click();
  await expect(page.getByText('2 / 21', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Referências incluídas' }).click();
  await expect(cards).toHaveCount(36);
  await nav.getByRole('button', { name: 'Conteúdos', exact: true }).click();
  await page.getByRole('button', { name: 'Abrir Carrossel de teste', exact: true }).click();
  const stages = page.getByRole('navigation', { name: 'Etapas' });
  await stages.getByRole('button', { name: /Carrossel$/ }).click();
  await expect(page.locator('.strip img')).toHaveCount(2);
  await stages.getByRole('button', { name: /Texto$/ }).click();
  await stages.getByRole('button', { name: /Carrossel$/ }).click();
  await expect(page.locator('.strip img')).toHaveCount(2);
  assert.deepEqual(errors, []);

  await app.evaluate(({ app }) => app.quit());
  await app.close().catch(() => {});
  app = null;
  await writeFile(join(userData, 'library', 'state.json'), '{"projects":[');
  app = await open();
  page = await app.firstWindow();
  await page.getByRole('heading', { name: 'O que vamos criar hoje?' }).waitFor();
  await page.getByRole('button', { name: 'Biblioteca', exact: true }).click();
  await expect(page.getByText('500 referências', { exact: true })).toBeVisible();
  const restored = await page.evaluate(async id => (await window.pacto.request('bootstrap')).projects.find(item => item.id === id), project.id);
  assert.ok(restored.slides.every(slide => slide.image?.startsWith('data:image/png;')));
  const startup = await readFile(join(userData, 'startup.log'), 'utf8');
  assert.match(startup, /"event":"aberto"/);
  console.log(JSON.stringify({ references: items.length, tilesPerPage: 24, catalogBytes: Buffer.byteLength(JSON.stringify(items)), importMs, packaged: Boolean(executablePath), artAfterNavigation: 2, recoveryAfterRestart: true }));
} finally {
  if (app) await app.evaluate(({ app }) => app.exit(0)).catch(() => {});
  await server?.close();
  if (dirname(userData) === temp) await rm(userData, { recursive: true, force: true, maxRetries: 3 }).catch(() => {});
}
